/** Four to six tiles per test: the steps that produced a screenshot, plus the bookends. */
function tiles(labels: string[], at: string): EvidenceTile[] {
  return labels.map((label, i) => ({ id: `ev-${i + 1}`, label, at }));
}

function step(s: Omit<TestStep, 'id'> & { id?: string }): TestStep {
  return { id: s.id ?? s.title.toLowerCase().replace(/[^a-z0-9]+/g, '-'), ...s };
}

