/** Every test's verdict for a run, from the ids that failed or were blocked. */
function verdicts(failed: string[], blocked: string[], skip: string[] = []): RunTestVerdict[] {
  return ORDERS_API_TESTS.filter((t) => !skip.includes(t.id)).map((t) => ({
    testId: t.id,
    name: t.name,
    verdict: failed.includes(t.id) ? 'failed' : blocked.includes(t.id) ? 'blocked' : 'passed',
    detail: failed.includes(t.id)
      ? t.steps.find((s) => !s.ok)?.title
      : blocked.includes(t.id)
        ? t.reason
        : undefined,
  }));
}

function tally(rows: RunTestVerdict[]) {
  return {
    passed: rows.filter((r) => r.verdict === 'passed').length,
    failed: rows.filter((r) => r.verdict === 'failed').length,
    blocked: rows.filter((r) => r.verdict === 'blocked').length,
  };
}

function run(
  base: Omit<Run, 'passed' | 'failed' | 'blocked' | 'tests' | 'repoId'>,
  failed: string[],
  blocked: string[],
  skip: string[] = [],
): Run {
  const tests = verdicts(failed, blocked, skip);
  return { ...base, repoId: 'orders-api', tests, ...tally(tests) };
}

