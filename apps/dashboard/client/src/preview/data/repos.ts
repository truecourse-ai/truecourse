/** A second attempt at the same board: the verdict table of one run, restamped. */
function restamp(base: Run, patch: Partial<Run> & { id: string }): Run {
  return { ...base, ...patch };
}

/** A run that never reached its first step: every scenario blocked, nothing passed. */
function couldNotStart(base: Run, patch: Partial<Run> & { id: string }, why: string): Run {
  const tests = base.tests.map((t) => ({ ...t, verdict: 'blocked' as const, detail: why }));
  return { ...base, ...patch, tests, passed: 0, failed: 0, blocked: tests.length };
}

